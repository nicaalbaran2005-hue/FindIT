-- ---------------------------------------------------------
-- Items (Report Lost Items / Report Found Items)
-- ---------------------------------------------------------
CREATE TABLE items (
    id           INT AUTO_INCREMENT PRIMARY KEY,
    user_id      INT NOT NULL,
    type         ENUM('lost','found') NOT NULL,
    title        VARCHAR(150) NOT NULL,
    description  TEXT,
    category     VARCHAR(80)  NOT NULL,
    location     VARCHAR(150) NOT NULL,
    item_date    DATE NOT NULL,
    item_time    TIME DEFAULT NULL,
    image_path   VARCHAR(255) DEFAULT NULL,
    status       ENUM('open','matched','claimed','closed') NOT NULL DEFAULT 'open',
    created_at   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- ---------------------------------------------------------
-- Matches (View/Review Match Results, generated by Match Score mechanism)
-- ---------------------------------------------------------
CREATE TABLE item_matches (
    id             INT AUTO_INCREMENT PRIMARY KEY,
    lost_item_id   INT NOT NULL,
    found_item_id  INT NOT NULL,
    location_score DECIMAL(5,2) NOT NULL,
    date_score     DECIMAL(5,2) NOT NULL,
    category_score DECIMAL(5,2) NOT NULL,
    total_score    DECIMAL(5,2) NOT NULL,
    status         ENUM('pending','reviewed','rejected','confirmed') NOT NULL DEFAULT 'pending',
    created_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (lost_item_id)  REFERENCES items(id) ON DELETE CASCADE,
    FOREIGN KEY (found_item_id) REFERENCES items(id) ON DELETE CASCADE,
    UNIQUE KEY uniq_pair (lost_item_id, found_item_id)
);

-- ---------------------------------------------------------
-- Claims (Submit Claim Request / Verify Claim Request)
-- ---------------------------------------------------------
CREATE TABLE claims (
    id                  INT AUTO_INCREMENT PRIMARY KEY,
    match_id            INT NOT NULL,
    claimant_id         INT NOT NULL,
    verification_detail TEXT NOT NULL,
    status              ENUM('pending','verified','rejected') NOT NULL DEFAULT 'pending',
    reviewed_by         INT DEFAULT NULL,
    reviewed_at         DATETIME DEFAULT NULL,
    created_at          DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (match_id) REFERENCES item_matches(id) ON DELETE CASCADE,
    FOREIGN KEY (claimant_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (reviewed_by) REFERENCES users(id) ON DELETE SET NULL
);

-- ---------------------------------------------------------
-- Notifications (Send/Receive Notifications)
-- ---------------------------------------------------------
CREATE TABLE notifications (
    id         INT AUTO_INCREMENT PRIMARY KEY,
    user_id    INT NOT NULL,
    message    VARCHAR(255) NOT NULL,
    link       VARCHAR(255) DEFAULT NULL,
    is_read    TINYINT(1) NOT NULL DEFAULT 0,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

