-- =========================================================
-- FindIT: Web-Based Lost and Found Management System
-- Database Schema (MySQL / MariaDB)
-- =========================================================

CREATE DATABASE IF NOT EXISTS findit_db;
USE findit_db;

-- ---------------------------------------------------------
-- Users (Register/Login, Manage User Accounts)
-- ---------------------------------------------------------
CREATE TABLE users (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    full_name     VARCHAR(150) NOT NULL,
    email         VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    phone         VARCHAR(30)  DEFAULT NULL,
    role          ENUM('user','admin') NOT NULL DEFAULT 'user',
    status        ENUM('active','disabled') NOT NULL DEFAULT 'active',
    created_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------------------------------------------------------
-- Match weight settings (Admin: Set Match Criteria)
-- Location 40%, Date & Time 30%, Category 30% (defaults)
-- ---------------------------------------------------------
CREATE TABLE match_settings (
    id              INT AUTO_INCREMENT PRIMARY KEY,
    location_weight DECIMAL(4,2) NOT NULL DEFAULT 40.00,
    date_weight     DECIMAL(4,2) NOT NULL DEFAULT 30.00,
    category_weight DECIMAL(4,2) NOT NULL DEFAULT 30.00,
    updated_by      INT DEFAULT NULL,
    updated_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

